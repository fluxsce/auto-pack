-- 工作空间批量分支克隆记录

BEGIN;

CREATE TABLE IF NOT EXISTS AP_PACK_WORKSPACE_BRANCH_CLONE (
  rec_id TEXT NOT NULL PRIMARY KEY,
  workspace_rec_id TEXT NOT NULL,
  batch_num INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'running',
  source_branch TEXT NOT NULL DEFAULT '',
  target_branch TEXT NOT NULL DEFAULT '',
  cloned INTEGER NOT NULL DEFAULT 0,
  skipped INTEGER NOT NULL DEFAULT 0,
  failed INTEGER NOT NULL DEFAULT 0,
  message TEXT NOT NULL DEFAULT '',
  log_path TEXT NOT NULL DEFAULT '',
  started_at TEXT,
  finished_at TEXT,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE UNIQUE INDEX IF NOT EXISTS IX_AP_PACK_WORKSPACE_BRANCH_CLONE_NUM
  ON AP_PACK_WORKSPACE_BRANCH_CLONE(workspace_rec_id, batch_num);

CREATE INDEX IF NOT EXISTS IX_AP_PACK_WORKSPACE_BRANCH_CLONE_WS
  ON AP_PACK_WORKSPACE_BRANCH_CLONE(workspace_rec_id, created_at DESC);

COMMIT;
